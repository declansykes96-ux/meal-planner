/**
 * A practical, family-sized catalogue intended for Australian meal planning.
 * Quantities are a sensible starting point for the stated number of servings.
 */
export type CatalogueMeal = {
  name: string;
  description: string;
  instructions: string;
  prepTimeMinutes: number;
  cookTimeMinutes: number;
  servings: number;
  tags: string[];
  ingredients: { name: string; quantity?: number; unit?: string }[];
  breakfastSuitability: number;
  lunchSuitability: number;
  dinnerSuitability: number;
  goodForLeftovers?: boolean;
  leftoverStorageDays?: number;
  reheatsWell?: boolean;
  batchFriendly?: boolean;
};

type Ingredient = CatalogueMeal["ingredients"][number];
type Variant = readonly [name: string, main: string, quantity: number, unit: string];

type MealGroup = {
  description: string;
  instructions: string;
  prepTimeMinutes: number;
  cookTimeMinutes: number;
  servings: number;
  tags: string[];
  ingredients: Ingredient[];
  suitability: readonly [number, number, number];
  leftovers?: boolean;
  reheats?: boolean;
  batch?: boolean;
  variants: readonly Variant[];
};

const ingredient = (name: string, quantity?: number, unit?: string): Ingredient =>
  quantity === undefined ? { name } : { name, quantity, unit };

const makeMeals = (group: MealGroup): CatalogueMeal[] =>
  group.variants.map(([name, main, quantity, unit]) => ({
    name,
    description: group.description,
    instructions: group.instructions,
    prepTimeMinutes: group.prepTimeMinutes,
    cookTimeMinutes: group.cookTimeMinutes,
    servings: group.servings,
    tags: group.tags,
    ingredients: [ingredient(main, quantity, unit), ...group.ingredients],
    breakfastSuitability: group.suitability[0],
    lunchSuitability: group.suitability[1],
    dinnerSuitability: group.suitability[2],
    goodForLeftovers: group.leftovers,
    leftoverStorageDays: group.leftovers ? 3 : undefined,
    reheatsWell: group.reheats,
    batchFriendly: group.batch,
  }));

